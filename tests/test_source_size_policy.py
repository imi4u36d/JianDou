def test_refactored_large_files_do_not_regrow() -> None:
    over_budget: list[str] = []
    for relative_path, budget in RATCHETED_LINE_BUDGETS.items():
        line_count = len((REPO_ROOT / relative_path).read_text(encoding="utf-8").splitlines())
        if line_count > budget:
            over_budget.append(f"{relative_path}: {line_count} > {budget}")

    assert over_budget == [], (
        "Lower a module's responsibilities or intentionally revise its documented budget:\n" + "\n".join(over_budget)
    )


def test_superseded_large_frontend_modules_stay_removed() -> None:
    assert [path for path in REMOVED_LEGACY_FILES if (REPO_ROOT / path).exists()] == []
